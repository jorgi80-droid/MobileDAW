// Counts the project's code by language (bytes, like GitHub's Languages bar) and writes js/aboutdata.js for the About tab.
// Run after code changes, before tools/build.mjs:  node tools/langstats.mjs
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const KIND = { '.js': 'JavaScript', '.mjs': 'JavaScript', '.css': 'CSS', '.html': 'HTML' };
const COLOR = { JavaScript: '#f1e05a', CSS: '#563d7c', HTML: '#e34c26' };   // GitHub linguist colours
const SKIP = new Set(['node_modules', 'demos', 'icons', '.git']);
const acc = {};
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const f = path.join(d, e.name);
    if (e.isDirectory()) { walk(f); continue; }
    if (path.relative(root, f) === path.join('js', 'aboutdata.js')) continue;
    const k = KIND[path.extname(e.name)]; if (!k) continue;
    const buf = fs.readFileSync(f), a = acc[k] || (acc[k] = { name: k, bytes: 0, lines: 0, files: 0, color: COLOR[k] });
    a.bytes += buf.length; a.files++; a.lines += buf.toString('utf8').split('\n').length;
  }
})(root);
const langs = Object.values(acc).sort((a, b) => b.bytes - a.bytes);
fs.writeFileSync(path.join(root, 'js', 'aboutdata.js'), `// Generated by tools/langstats.mjs - do not edit by hand.\nexport const LANGS = ${JSON.stringify(langs)};\n`);
console.log(langs.map((l) => `${l.name} ${l.bytes}`).join(', '));
